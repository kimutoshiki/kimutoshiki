export function buildSoftwareStatue(scene, x, y, z, height, id, yaw = 0) {
  const scale = height / 4096;
  // The canvas camera looks along +Z with +X to screen-right. Make the
  // figure face that camera while keeping the cane on the viewer’s left.
  const sin = Math.sin(yaw), cos = Math.cos(yaw);
  const points = [];
  for (let i = 0; i < vertices.length; i += 3) {
    const px = vertices[i] * scale, pz = -vertices[i + 2] * scale;
    points.push([x + px * cos + pz * sin, y + vertices[i + 1] * scale, z - px * sin + pz * cos]);
  }
  const options = {id};
  for (let i = 0; i < triangles.length; i += 4) {
    scene.face([points[triangles[i]], points[triangles[i + 1]], points[triangles[i + 2]]],
      patina[triangles[i + 3]], options);
  }
}
