def material(name,colors=False):
    m=bpy.data.materials.new(name);m.use_nodes=True
    nodes=m.node_tree.nodes;shader=nodes.get('Principled BSDF')
    shader.inputs['Roughness'].default_value=.89
    if colors:
        attr=nodes.new('ShaderNodeVertexColor');attr.layer_name='Pigment';m.node_tree.links.new(attr.outputs['Color'],shader.inputs['Base Color'])
    return m,shader

def ground_material(kind,temp):
    # Seamless metre-scale material samples. Only surface albedo is baked.
    # No camera photographs or screen-facing textures are used for scenery.
    m,shader=material(kind)
    a={'court':[165,158,141],'walk':[175,171,159],'street':[99,100,96],'shore':[91,105,67],'sea':[52,111,133],'sand':[191,171,136]}[kind]
    size=256;rng=np.random.default_rng(1631)
    y,x=np.mgrid[0:size,0:size]
    grain=(rng.random((size,size))-.50)*({'sea':4,'shore':23,'street':23}.get(kind,15))
    broad=2*np.sin(x*2*np.pi/size*3+np.sin(y*2*np.pi/size*2))+2.1*np.sin((x+y)*2*np.pi/size*2)
    albedo=np.array(a)[None,None,:]+(grain+broad)[:,:,None]
    if kind=='walk':
        row=y//32;col=((x+(row%2)*32)%size)//64;dx=(x+(row%2)*32)%64;dy=y%32
        joint=np.minimum(np.minimum(dx,63-dx),np.minimum(dy,31-dy))
        albedo+=(np.where(joint==0,-30,np.where(joint==1,4,0))+((row*17+col*7)%9-4)*1.6)[:,:,None]
    if kind=='sand':
        albedo+=((rng.random((size,size))>.93)*-24)[:,:,None]
    if kind=='sea':
        crest=np.maximum(0,np.sin(y/size*np.pi*24+1.3*np.sin(x/size*np.pi*8)+np.sin(y/size*np.pi*4)))**16
        albedo+=crest[:,:,None]*(12+12*np.sin(x/size*np.pi*4))[:,:,None]
        shader.inputs['Roughness'].default_value=.38;shader.inputs['Metallic'].default_value=.17
    rgba=np.ones((size,size,4),dtype=np.float32);c=np.clip(albedo/255,0,1)
    rgba[:,:,:3]=c  # The generated byte image accepts encoded sRGB channel values.
    image=bpy.data.images.new(kind+' aggregate · repeating surface',size,size,alpha=False)
    image.pixels.foreach_set(rgba.reshape(-1));image.file_format='JPEG';image.filepath_raw=str(temp/(kind+'.jpg'));image.save();image.pack()
    tex=m.node_tree.nodes.new('ShaderNodeTexImage');tex.image=image;tex.extension='REPEAT';m.node_tree.links.new(tex.outputs['Color'],shader.inputs['Base Color'])
    return m

def guide_mesh(rec,buffer,m,parent):
    def field(name,dtype):
        off,n=rec[name];return np.frombuffer(buffer,dtype=dtype,count=n,offset=off)
    p=field('p','<f4').reshape(-1,3);idx=field('idx','<u4').reshape(-1,3);uv=field('uv','<f4').reshape(-1,2);colors=field('c','<f4').reshape(-1,3)
    me=bpy.data.meshes.new(rec['name']);me.from_pydata(p.tolist(),[],idx.tolist());me.materials.append(m);me.update()
    ids=np.empty(len(me.loops),dtype=np.int32);me.loops.foreach_get('vertex_index',ids)
    if len(colors):
        attr=me.color_attributes.new(name='Pigment',type='BYTE_COLOR',domain='CORNER')
        rgba=np.ones((len(ids),4),dtype=np.float32);rgba[:,:3]=colors[ids];attr.data.foreach_set('color',rgba.reshape(-1))
    if len(uv):
        tex=me.uv_layers.new(name='Metric UV');tex.data.foreach_set('uv',uv[ids].reshape(-1))
    ob=bpy.data.objects.new(rec['name'],me);bpy.context.collection.objects.link(ob);ob.parent=parent

